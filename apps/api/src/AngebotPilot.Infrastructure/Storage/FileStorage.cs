using System.Collections.Concurrent;
using System.Runtime.CompilerServices;
using System.Text.RegularExpressions;
using Amazon.Runtime;
using Amazon.S3;
using Amazon.S3.Model;
using AngebotPilot.Application.Abstractions;

namespace AngebotPilot.Infrastructure.Storage;

public sealed class StorageOptions
{
    public const string Section = "Storage";

    /// <summary>"S3" (Cloudflare R2 or any S3-compatible service), "Local" (disk) or "Memory" (tests).</summary>
    public string Provider { get; set; } = "Local";

    public string LocalRoot { get; set; } = "App_Data/storage";

    public string? S3ServiceUrl { get; set; }

    public string? S3Bucket { get; set; }

    public string? S3AccessKeyId { get; set; }

    public string? S3SecretAccessKey { get; set; }

    /// <summary>"auto" for Cloudflare R2.</summary>
    public string S3Region { get; set; } = "auto";
}

internal static partial class ObjectKeys
{
    [GeneratedRegex(@"^[a-z0-9][a-z0-9/._-]{0,299}$")]
    private static partial Regex Allowed();

    /// <summary>Object keys are generated by the server; this guard rejects anything that could escape the storage root.</summary>
    public static string Validate(string key)
    {
        if (!Allowed().IsMatch(key) || key.Contains("..", StringComparison.Ordinal) || key.Contains("//", StringComparison.Ordinal))
        {
            throw new ArgumentException("Invalid object key.", nameof(key));
        }

        return key;
    }
}

/// <summary>Stores objects on the local file system (development, or hosts without object storage).</summary>
public sealed class LocalFileStorage : IFileStorageService
{
    private readonly string _root;

    public LocalFileStorage(string root)
    {
        _root = Path.GetFullPath(root);
        Directory.CreateDirectory(_root);
    }

    public async Task PutAsync(string objectKey, Stream content, string contentType, CancellationToken cancellationToken)
    {
        var path = PathFor(objectKey);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temp = path + ".tmp";
        await using (var file = File.Create(temp))
        {
            await content.CopyToAsync(file, cancellationToken);
        }

        File.Move(temp, path, overwrite: true);
    }

    public Task<StoredObject?> GetAsync(string objectKey, CancellationToken cancellationToken)
    {
        var path = PathFor(objectKey);
        if (!File.Exists(path))
        {
            return Task.FromResult<StoredObject?>(null);
        }

        var stream = File.OpenRead(path);
        return Task.FromResult<StoredObject?>(new StoredObject(stream, ContentTypeFor(objectKey), stream.Length));
    }

    public Task DeleteAsync(string objectKey, CancellationToken cancellationToken)
    {
        var path = PathFor(objectKey);
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        return Task.CompletedTask;
    }

    public Task<bool> ExistsAsync(string objectKey, CancellationToken cancellationToken) => Task.FromResult(File.Exists(PathFor(objectKey)));

    public async IAsyncEnumerable<string> ListAsync(string prefix, [EnumeratorCancellation] CancellationToken cancellationToken)
    {
        var dir = Path.Combine(_root, prefix.Replace('/', Path.DirectorySeparatorChar));
        if (!Directory.Exists(dir))
        {
            yield break;
        }

        foreach (var file in Directory.EnumerateFiles(dir, "*", SearchOption.AllDirectories))
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (file.EndsWith(".tmp", StringComparison.Ordinal))
            {
                continue;
            }

            yield return Path.GetRelativePath(_root, file).Replace(Path.DirectorySeparatorChar, '/');
        }

        await Task.CompletedTask;
    }

    public Task<Uri?> GetPresignedDownloadUrlAsync(string objectKey, string downloadFileName, TimeSpan lifetime, CancellationToken cancellationToken) =>
        Task.FromResult<Uri?>(null);

    private string PathFor(string key)
    {
        var full = Path.GetFullPath(Path.Combine(_root, ObjectKeys.Validate(key).Replace('/', Path.DirectorySeparatorChar)));
        if (!full.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
        {
            throw new ArgumentException("Invalid object key.", nameof(key));
        }

        return full;
    }

    internal static string ContentTypeFor(string key) => Path.GetExtension(key).ToLowerInvariant() switch
    {
        ".pdf" => "application/pdf",
        ".png" => "image/png",
        ".jpg" or ".jpeg" => "image/jpeg",
        _ => "application/octet-stream",
    };
}

/// <summary>In-memory storage for automated tests.</summary>
public sealed class InMemoryFileStorage : IFileStorageService
{
    private readonly ConcurrentDictionary<string, (byte[] Data, string ContentType)> _objects = new();

    public IReadOnlyCollection<string> Keys => _objects.Keys.ToList();

    public async Task PutAsync(string objectKey, Stream content, string contentType, CancellationToken cancellationToken)
    {
        using var ms = new MemoryStream();
        await content.CopyToAsync(ms, cancellationToken);
        _objects[ObjectKeys.Validate(objectKey)] = (ms.ToArray(), contentType);
    }

    public Task<StoredObject?> GetAsync(string objectKey, CancellationToken cancellationToken) =>
        Task.FromResult(_objects.TryGetValue(objectKey, out var o) ? new StoredObject(new MemoryStream(o.Data, writable: false), o.ContentType, o.Data.LongLength) : null);

    public Task DeleteAsync(string objectKey, CancellationToken cancellationToken)
    {
        _objects.TryRemove(objectKey, out _);
        return Task.CompletedTask;
    }

    public Task<bool> ExistsAsync(string objectKey, CancellationToken cancellationToken) => Task.FromResult(_objects.ContainsKey(objectKey));

    public async IAsyncEnumerable<string> ListAsync(string prefix, [EnumeratorCancellation] CancellationToken cancellationToken)
    {
        foreach (var key in _objects.Keys.Where(k => k.StartsWith(prefix, StringComparison.Ordinal)))
        {
            yield return key;
        }

        await Task.CompletedTask;
    }

    public Task<Uri?> GetPresignedDownloadUrlAsync(string objectKey, string downloadFileName, TimeSpan lifetime, CancellationToken cancellationToken) =>
        Task.FromResult<Uri?>(null);
}

/// <summary>
/// S3-compatible storage. Configured for Cloudflare R2: region "auto", path-style addressing and checksums only
/// when required (R2 does not support all AWS SDK v4 default checksum behaviours). Objects are always private.
/// </summary>
public sealed class S3FileStorage : IFileStorageService, IDisposable
{
    private readonly AmazonS3Client _client;
    private readonly string _bucket;

    public S3FileStorage(StorageOptions options)
    {
        if (string.IsNullOrWhiteSpace(options.S3ServiceUrl) || string.IsNullOrWhiteSpace(options.S3Bucket)
            || string.IsNullOrWhiteSpace(options.S3AccessKeyId) || string.IsNullOrWhiteSpace(options.S3SecretAccessKey))
        {
            throw new InvalidOperationException("Storage:Provider=S3 requires S3ServiceUrl, S3Bucket, S3AccessKeyId and S3SecretAccessKey.");
        }

        var config = new AmazonS3Config
        {
            ServiceURL = options.S3ServiceUrl,
            AuthenticationRegion = options.S3Region,
            ForcePathStyle = true,
            RequestChecksumCalculation = RequestChecksumCalculation.WHEN_REQUIRED,
            ResponseChecksumValidation = ResponseChecksumValidation.WHEN_REQUIRED,
        };
        _client = new AmazonS3Client(new BasicAWSCredentials(options.S3AccessKeyId, options.S3SecretAccessKey), config);
        _bucket = options.S3Bucket;
    }

    public async Task PutAsync(string objectKey, Stream content, string contentType, CancellationToken cancellationToken)
    {
        // Buffer so the SDK knows the content length (R2 rejects streaming chunked uploads without it).
        using var ms = new MemoryStream();
        await content.CopyToAsync(ms, cancellationToken);
        ms.Position = 0;
        await _client.PutObjectAsync(new PutObjectRequest
        {
            BucketName = _bucket,
            Key = ObjectKeys.Validate(objectKey),
            InputStream = ms,
            ContentType = contentType,
            DisablePayloadSigning = true,
            AutoCloseStream = false,
        }, cancellationToken);
    }

    public async Task<StoredObject?> GetAsync(string objectKey, CancellationToken cancellationToken)
    {
        try
        {
            var response = await _client.GetObjectAsync(_bucket, ObjectKeys.Validate(objectKey), cancellationToken);
            return new StoredObject(response.ResponseStream, response.Headers.ContentType ?? LocalFileStorage.ContentTypeFor(objectKey), response.ContentLength);
        }
        catch (AmazonS3Exception e) when (e.StatusCode == System.Net.HttpStatusCode.NotFound)
        {
            return null;
        }
    }

    public Task DeleteAsync(string objectKey, CancellationToken cancellationToken) =>
        _client.DeleteObjectAsync(_bucket, ObjectKeys.Validate(objectKey), cancellationToken);

    public async Task<bool> ExistsAsync(string objectKey, CancellationToken cancellationToken)
    {
        try
        {
            await _client.GetObjectMetadataAsync(_bucket, ObjectKeys.Validate(objectKey), cancellationToken);
            return true;
        }
        catch (AmazonS3Exception e) when (e.StatusCode == System.Net.HttpStatusCode.NotFound)
        {
            return false;
        }
    }

    public async IAsyncEnumerable<string> ListAsync(string prefix, [EnumeratorCancellation] CancellationToken cancellationToken)
    {
        string? continuation = null;
        do
        {
            var response = await _client.ListObjectsV2Async(new ListObjectsV2Request { BucketName = _bucket, Prefix = prefix, ContinuationToken = continuation }, cancellationToken);
            foreach (var o in response.S3Objects ?? [])
            {
                yield return o.Key;
            }

            continuation = response.IsTruncated == true ? response.NextContinuationToken : null;
        }
        while (continuation is not null);
    }

    public async Task<Uri?> GetPresignedDownloadUrlAsync(string objectKey, string downloadFileName, TimeSpan lifetime, CancellationToken cancellationToken)
    {
        var url = await _client.GetPreSignedURLAsync(new GetPreSignedUrlRequest
        {
            BucketName = _bucket,
            Key = ObjectKeys.Validate(objectKey),
            Expires = DateTime.UtcNow.Add(lifetime > TimeSpan.FromHours(1) ? TimeSpan.FromHours(1) : lifetime),
            Verb = HttpVerb.GET,
            ResponseHeaderOverrides = { ContentDisposition = $"attachment; filename=\"{downloadFileName}\"" },
        });
        return new Uri(url);
    }

    public void Dispose() => _client.Dispose();
}
